using System.Collections.Generic;
using UnityEngine;
using UnityEngine.XR.ARSubsystems;

namespace Erasmus.ARToolkit
{
    /// <summary>
    /// All user content and behaviour settings for the toolkit. Edited from the
    /// Content tab of the toolkit window. Treated as read-only at runtime.
    /// </summary>
    [CreateAssetMenu(menuName = "Erasmus AR Toolkit/Toolkit Config", fileName = "ARToolkitConfig")]
    public sealed class ARToolkitConfig : ScriptableObject
    {
        [Header("Content")]
        [SerializeField] List<PlaceableItem> placeables = new List<PlaceableItem>();
        [SerializeField] List<ImageTargetItem> imageTargets = new List<ImageTargetItem>();
        [SerializeField, Tooltip("Generated by the toolkit window from the image targets above.")]
        XRReferenceImageLibrary imageLibrary;

        [Header("Placement")]
        [SerializeField, Min(1)] int maxPlacedObjects = 10;
        [SerializeField, Tooltip("Min/max scale multiplier the user can reach with pinch or Shift+scroll.")]
        Vector2 scaleLimits = new Vector2(0.2f, 5f);

        [Header("Behaviour")]
        [SerializeField] bool showPlanesOnStart = true;
        [SerializeField, Tooltip("Real objects (furniture, people, hands) hide virtual objects and surface grids " +
                                 "behind them. Needs a phone with ARCore Depth; other phones show everything.")]
        bool realWorldOcclusion = true;
        [SerializeField] ModeOverride modeOverride = ModeOverride.Auto;

        [Header("Room Scan")]
        [SerializeField, Tooltip("Shows what the room scan measures (depth mapping, floor height, timings) on the " +
                                 "HUD while scanning. The same line is always written to the log.")]
        bool showScanDiagnostics;
        [SerializeField, Range(0.1f, 1f), Tooltip("Distance between the grid lines on floors and tables, in meters.")]
        float gridCellSize = 0.25f;
        [SerializeField, Tooltip("The room scan looks for the walls of the room and shows them. ARCore detects " +
                                 "vertical planes for that, which costs a little speed.")]
        bool detectWalls = true;

        [Header("Camera")]
        [SerializeField, Tooltip("When real AR is not available (PC, Editor, phones without ARCore), show the " +
                                 "device camera behind the scene: the PC webcam or the phone's back camera.")]
        bool useDeviceCamera = true;
        [SerializeField, Tooltip("Optional exact camera name to use first (see the Console for the list). " +
                                 "Empty: PCs use the first webcam, phones use the back camera.")]
        string preferredCameraName = string.Empty;

        [Header("Desktop Mode")]
        [SerializeField, Tooltip("Lay image targets on the virtual ground so they can be tested without a phone.")]
        bool desktopSimulateImageTargets = true;

        public IReadOnlyList<PlaceableItem> Placeables => placeables;
        public IReadOnlyList<ImageTargetItem> ImageTargets => imageTargets;
        public XRReferenceImageLibrary ImageLibrary => imageLibrary;
        public int MaxPlacedObjects => maxPlacedObjects;
        public Vector2 ScaleLimits => scaleLimits;
        public bool ShowPlanesOnStart => showPlanesOnStart;
        public bool RealWorldOcclusion => realWorldOcclusion;
        public ModeOverride ModeOverride => modeOverride;
        public bool ShowScanDiagnostics => showScanDiagnostics;

        /// <summary>Distance between the grid lines on floors and tables, in meters.</summary>
        public float GridCellSize => Mathf.Clamp(gridCellSize, 0.1f, 1f);

        /// <summary>The room scan looks for the walls of the room.</summary>
        public bool DetectWalls => detectWalls;
        public bool UseDeviceCamera => useDeviceCamera;
        public string PreferredCameraName => preferredCameraName ?? string.Empty;
        public bool DesktopSimulateImageTargets => desktopSimulateImageTargets;

        /// <summary>Some placeable objects hang on walls (the phone then looks for walls too).</summary>
        public bool HasWallPlaceables
        {
            get
            {
                foreach (var item in placeables)
                {
                    if (item != null && item.PlaceOn == PlaceOn.Wall)
                    {
                        return true;
                    }
                }

                return false;
            }
        }

        /// <summary>Editor and test helper. Runtime code never mutates the config.</summary>
        internal void SetContent(IEnumerable<PlaceableItem> newPlaceables, IEnumerable<ImageTargetItem> newImageTargets)
        {
            placeables = new List<PlaceableItem>(newPlaceables);
            imageTargets = new List<ImageTargetItem>(newImageTargets);
        }

        internal void SetImageLibrary(XRReferenceImageLibrary library)
        {
            imageLibrary = library;
        }

        internal void SetLimits(int maxObjects, Vector2 limits)
        {
            maxPlacedObjects = maxObjects;
            scaleLimits = limits;
        }
    }
}
